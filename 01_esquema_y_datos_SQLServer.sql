CREATE TABLE dbo.autores (
    id_autor INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    nombre_autor VARCHAR(100) NOT NULL,
    nacionalidad VARCHAR(100) NULL
);
GO
CREATE TABLE dbo.editoriales (
    id_editorial INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    nombre_editorial VARCHAR(150) NOT NULL,
    pais VARCHAR(50) NULL
);
GO
CREATE TABLE dbo.categorias (
    id_categoria INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    nombre_categoria VARCHAR(100) NOT NULL
);
GO
CREATE TABLE dbo.empleados (
    id_empleado INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    cargo VARCHAR(50) NULL
);
GO
CREATE TABLE dbo.socios (
    id_socio INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    correo VARCHAR(100) NULL UNIQUE,
    esta_solvente BIT NOT NULL CONSTRAINT DF_socios_solvente DEFAULT (1)
);
GO
CREATE TABLE dbo.libros (
    isbn VARCHAR(20) NOT NULL PRIMARY KEY,
    titulo VARCHAR(255) NOT NULL,
    id_editorial INT NULL,
    id_categoria INT NULL,
    anio_publicacion INT NULL,
    CONSTRAINT FK_libros_editoriales FOREIGN KEY (id_editorial) REFERENCES dbo.editoriales(id_editorial) ON DELETE SET NULL,
    CONSTRAINT FK_libros_categorias FOREIGN KEY (id_categoria) REFERENCES dbo.categorias(id_categoria) ON DELETE SET NULL
);
GO
CREATE TABLE dbo.libro_autor (
    isbn VARCHAR(20) NOT NULL,
    id_autor INT NOT NULL,
    CONSTRAINT PK_libro_autor PRIMARY KEY (isbn, id_autor),
    CONSTRAINT FK_libro_autor_libros FOREIGN KEY (isbn) REFERENCES dbo.libros(isbn) ON DELETE CASCADE,
    CONSTRAINT FK_libro_autor_autores FOREIGN KEY (id_autor) REFERENCES dbo.autores(id_autor) ON DELETE CASCADE
);
GO
CREATE TABLE dbo.ejemplares (
    id_ejemplar INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    isbn VARCHAR(20) NULL,
    estado VARCHAR(20) NOT NULL CONSTRAINT DF_ejemplares_estado DEFAULT ('Disponible'),
    CONSTRAINT FK_ejemplares_libros FOREIGN KEY (isbn) REFERENCES dbo.libros(isbn) ON DELETE CASCADE,
    CONSTRAINT chk_estado_ejemplar CHECK (estado IN ('Disponible', 'Prestado', 'Reservado', 'Mantenimiento'))
);
GO
CREATE TABLE dbo.prestamos (
    id_prestamo INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    id_ejemplar INT NULL,
    id_socio INT NULL,
    id_empleado INT NULL,
    fecha_salida DATE NOT NULL CONSTRAINT DF_prestamos_salida DEFAULT (CONVERT(date, GETDATE())),
    fecha_limite DATE NOT NULL,
    CONSTRAINT FK_prestamos_ejemplares FOREIGN KEY (id_ejemplar) REFERENCES dbo.ejemplares(id_ejemplar),
    CONSTRAINT FK_prestamos_socios FOREIGN KEY (id_socio) REFERENCES dbo.socios(id_socio),
    CONSTRAINT FK_prestamos_empleados FOREIGN KEY (id_empleado) REFERENCES dbo.empleados(id_empleado)
);
GO
CREATE TABLE dbo.devoluciones (
    id_devolucion INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    id_prestamo INT NULL,
    fecha_entrega_real DATE NOT NULL CONSTRAINT DF_devoluciones_fecha DEFAULT (CONVERT(date, GETDATE())),
    observaciones NVARCHAR(MAX) NULL,
    CONSTRAINT FK_devoluciones_prestamos FOREIGN KEY (id_prestamo) REFERENCES dbo.prestamos(id_prestamo) ON DELETE CASCADE
);
GO
CREATE TABLE dbo.multas (
    id_multa INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    id_socio INT NULL,
    id_prestamo INT NULL,
    monto DECIMAL(10,2) NOT NULL,
    estado_pago BIT NOT NULL CONSTRAINT DF_multas_estado DEFAULT (0),
    CONSTRAINT FK_multas_socios FOREIGN KEY (id_socio) REFERENCES dbo.socios(id_socio) ON DELETE CASCADE,
    CONSTRAINT FK_multas_prestamos FOREIGN KEY (id_prestamo) REFERENCES dbo.prestamos(id_prestamo)
);
GO


